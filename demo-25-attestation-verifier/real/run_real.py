#!/usr/bin/env python3
"""Fetch REAL public data for this demo and analyse it. Writes data/real/*.json and RESULTS.md.
Run from the demo folder: python3 real/run_real.py"""
import json, urllib.request, urllib.parse, time, datetime, os, collections, re, statistics
UA={"User-Agent":"agentic-security-demos research"}
def get(url, data=None, timeout=90, raw=False):
    err=None
    for i in range(5):
        try:
            req=urllib.request.Request(url, data=json.dumps(data).encode() if data else None, headers={**UA, **({"Content-Type":"application/json"} if data else {})})
            b=urllib.request.urlopen(req, timeout=timeout).read()
            return b.decode() if raw else json.loads(b)
        except Exception as e:
            err=e; time.sleep(7*(i+1))
    raise err
TODAY=datetime.date.today().isoformat()
def save(name, obj):
    os.makedirs("data/real", exist_ok=True)
    json.dump(obj, open(f"data/real/{name}","w"), indent=1, sort_keys=True)
def osv(eco, pkg):
    r=get("https://api.osv.dev/v1/query", {"package":{"name":pkg,"ecosystem":eco}})
    return [{"id":v["id"],"aliases":v.get("aliases",[]),"summary":v.get("summary",""),"published":v.get("published"),
             "severity":v.get("database_specific",{}).get("severity"),"cwe":v.get("database_specific",{}).get("cwe_ids",[]),
             "package":pkg,"ecosystem":eco} for v in r.get("vulns",[])]
def nvd(phrase):
    out=[];start=0
    while True:
        q=urllib.parse.urlencode({"keywordSearch":phrase,"keywordExactMatch":"","resultsPerPage":2000,"startIndex":start}).replace("keywordExactMatch=","keywordExactMatch")
        r=get("https://services.nvd.nist.gov/rest/json/cves/2.0?"+q)
        for v in r["vulnerabilities"]:
            c=v["cve"]; d=[x["value"] for x in c["descriptions"] if x["lang"]=="en"][0]
            cw=sorted({x["description"][0]["value"] for x in c.get("weaknesses",[])})
            out.append({"id":c["id"],"published":c["published"],"description":d,"cwe":cw})
        start+=r["resultsPerPage"]
        if start>=r["totalResults"]: break
        time.sleep(7)
    return out
def results(title, lines):
    open("RESULTS.md","w").write(f"# {title}\n\nGenerated by `real/run_real.py` on {TODAY}. Data are real public records (see DATA_SOURCES.md); nothing here is simulated. The bundled `fixtures/` remain SYNTHETIC teaching fixtures and are not used in these numbers.\n\n"+"\n".join(lines)+"\n")

# npm provenance/attestation coverage for the most-depended-upon packages
pkgs=["lodash","react","chalk","tslib","axios","commander","debug","express","typescript","semver","uuid","glob","yargs","fs-extra","dotenv","zod","rxjs","prettier","eslint","webpack","vite","next","vue","@types/node","jest","esbuild","rollup","ws","minimist","mkdirp","@modelcontextprotocol/sdk","openai","@anthropic-ai/sdk","langchain","@langchain/core","ai","sigstore","npm","node-fetch","body-parser"]
rows=[]
for p in pkgs:
    m=get("https://registry.npmjs.org/"+p.replace("/","%2f"))
    v=m["dist-tags"]["latest"]; dist=m["versions"][v].get("dist",{})
    att=dist.get("attestations")
    pt=None
    if att:
        try:
            a=get(att["url"]); pt=sorted({x["predicateType"] for x in a.get("attestations",[])})
        except Exception as e: pt=["fetch-error"]
    rows.append({"package":p,"latest":v,"has_attestations":bool(att),"predicate_types":pt,"has_signatures":bool(dist.get("signatures"))})
    time.sleep(0.3)
save("npm_attestations.json",{"retrieved":TODAY,"rows":rows})
n=len(rows); a=sum(r["has_attestations"] for r in rows); s=sum(r["has_signatures"] for r in rows)
slsa=sum(1 for r in rows if r["predicate_types"] and any("slsa" in t for t in r["predicate_types"]))
L=["## npm provenance coverage (latest versions, %d widely used packages)"%n,"",f"- Registry signatures present: {s}/{n}",f"- Sigstore attestations present: {a}/{n} ({100*a/n:.0f}%)",f"- Of those, with a SLSA provenance predicate: {slsa}/{n}","","| package | latest | attestations | predicate types |","|---|---|---|---|"]
L+= [f"| {r['package']} | {r['latest']} | {'yes' if r['has_attestations'] else 'no'} | {', '.join(r['predicate_types'] or [])} |" for r in rows]
L+=["","Package list chosen by the author as widely used and agent-relevant; it is a convenience sample, not a random sample. Signature/attestation presence is not verification: the verifier in `student/` should be run against these bundles as the next step."]
results("Demo 25 real data: npm attestation coverage", L)
