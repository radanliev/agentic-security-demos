#!/usr/bin/env python3
"""Fetch REAL public data for this demo and analyse it. Writes data/real/*.json and RESULTS.md.
Run from the demo folder: python3 real/run_real.py"""
import json, urllib.request, urllib.parse, time, datetime, os, collections, re, statistics
UA={"User-Agent":"agentic-security-demos research"}
def get(url, data=None, timeout=90, raw=False):
    err=None
    for i in range(5):
        try:
            req=urllib.request.Request(url, data=json.dumps(data).encode() if data else None, headers={**UA, **({"Content-Type":"application/json"} if data else {})})
            b=urllib.request.urlopen(req, timeout=timeout).read()
            return b.decode() if raw else json.loads(b)
        except Exception as e:
            err=e; time.sleep(7*(i+1))
    raise err
TODAY=datetime.date.today().isoformat()
def save(name, obj):
    os.makedirs("data/real", exist_ok=True)
    json.dump(obj, open(f"data/real/{name}","w"), indent=1, sort_keys=True)
def osv(eco, pkg):
    r=get("https://api.osv.dev/v1/query", {"package":{"name":pkg,"ecosystem":eco}})
    return [{"id":v["id"],"aliases":v.get("aliases",[]),"summary":v.get("summary",""),"published":v.get("published"),
             "severity":v.get("database_specific",{}).get("severity"),"cwe":v.get("database_specific",{}).get("cwe_ids",[]),
             "package":pkg,"ecosystem":eco} for v in r.get("vulns",[])]
def nvd(phrase):
    out=[];start=0
    while True:
        q=urllib.parse.urlencode({"keywordSearch":phrase,"keywordExactMatch":"","resultsPerPage":2000,"startIndex":start}).replace("keywordExactMatch=","keywordExactMatch")
        r=get("https://services.nvd.nist.gov/rest/json/cves/2.0?"+q)
        for v in r["vulnerabilities"]:
            c=v["cve"]; d=[x["value"] for x in c["descriptions"] if x["lang"]=="en"][0]
            cw=sorted({x["description"][0]["value"] for x in c.get("weaknesses",[])})
            out.append({"id":c["id"],"published":c["published"],"description":d,"cwe":cw})
        start+=r["resultsPerPage"]
        if start>=r["totalResults"]: break
        time.sleep(7)
    return out
def results(title, lines):
    open("RESULTS.md","w").write(f"# {title}\n\nGenerated by `real/run_real.py` on {TODAY}. Data are real public records (see DATA_SOURCES.md); nothing here is simulated. The bundled `fixtures/` remain SYNTHETIC teaching fixtures and are not used in these numbers.\n\n"+"\n".join(lines)+"\n")

targets=[("PyPI","vllm"),("PyPI","ollama"),("Go","github.com/ollama/ollama"),("PyPI","langchain"),("PyPI","langchain-community"),("PyPI","llama-index"),("PyPI","gradio"),("PyPI","mlflow"),("PyPI","ray"),("PyPI","text-generation"),("PyPI","litellm"),("PyPI","open-webui"),("PyPI","transformers"),("PyPI","bentoml"),("PyPI","lmdeploy"),("PyPI","sglang")]
rows=[]
for e,p in targets: rows+=osv(e,p); time.sleep(0.3)
save("osv_llm_stack_advisories.json",{"retrieved":TODAY,"targets":targets,"rows":rows})
pat=r"default|unauthenticat|without auth|no auth|missing auth|0\.0\.0\.0|exposed|bind|trust_remote_code|pickle|deserial"
dflt=[r for r in rows if re.search(pat,r["summary"],re.I)]
by=collections.Counter(r["package"] for r in rows); byd=collections.Counter(r["package"] for r in dflt)
sev=collections.Counter(r["severity"] for r in rows)
L=[f"## OSV advisories across {len(targets)} LLM-serving and orchestration packages ({len(rows)} advisories)","",f"- Summaries matching a default/unauthenticated/exposure/deserialisation pattern: {len(dflt)}/{len(rows)} ({100*len(dflt)/max(1,len(rows)):.0f}%)","- Severity labels: "+", ".join(f"{k}: {v}" for k,v in sev.most_common()),"","| package | advisories | default-or-exposure pattern |","|---|---|---|"]
L+=[f"| {p} | {by[p]} | {byd[p]} |" for e,p in targets]
L+=["","Regex pattern: `"+pat+"`. This is a screening filter for the operator census, not a classification; the 83 vs 51 discrepancy on branch sp27-c2/demo-30-draft is not resolved by this data."]
results("Demo 30 real data: LLM-stack advisories linked to insecure defaults (OSV)", L)
