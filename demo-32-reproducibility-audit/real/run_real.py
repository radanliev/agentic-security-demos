#!/usr/bin/env python3
"""Fetch REAL public data for this demo and analyse it. Writes data/real/*.json and RESULTS.md.
Run from the demo folder: python3 real/run_real.py"""
import json, urllib.request, urllib.parse, time, datetime, os, collections, re, statistics
UA={"User-Agent":"agentic-security-demos research"}
def get(url, data=None, timeout=90, raw=False):
    err=None
    for i in range(5):
        try:
            req=urllib.request.Request(url, data=json.dumps(data).encode() if data else None, headers={**UA, **({"Content-Type":"application/json"} if data else {})})
            b=urllib.request.urlopen(req, timeout=timeout).read()
            return b.decode() if raw else json.loads(b)
        except Exception as e:
            err=e; time.sleep(7*(i+1))
    raise err
TODAY=datetime.date.today().isoformat()
def save(name, obj):
    os.makedirs("data/real", exist_ok=True)
    json.dump(obj, open(f"data/real/{name}","w"), indent=1, sort_keys=True)
def osv(eco, pkg):
    r=get("https://api.osv.dev/v1/query", {"package":{"name":pkg,"ecosystem":eco}})
    return [{"id":v["id"],"aliases":v.get("aliases",[]),"summary":v.get("summary",""),"published":v.get("published"),
             "severity":v.get("database_specific",{}).get("severity"),"cwe":v.get("database_specific",{}).get("cwe_ids",[]),
             "package":pkg,"ecosystem":eco} for v in r.get("vulns",[])]
def nvd(phrase):
    out=[];start=0
    while True:
        q=urllib.parse.urlencode({"keywordSearch":phrase,"keywordExactMatch":"","resultsPerPage":2000,"startIndex":start}).replace("keywordExactMatch=","keywordExactMatch")
        r=get("https://services.nvd.nist.gov/rest/json/cves/2.0?"+q)
        for v in r["vulnerabilities"]:
            c=v["cve"]; d=[x["value"] for x in c["descriptions"] if x["lang"]=="en"][0]
            cw=sorted({x["description"][0]["value"] for x in c.get("weaknesses",[])})
            out.append({"id":c["id"],"published":c["published"],"description":d,"cwe":cw})
        start+=r["resultsPerPage"]
        if start>=r["totalResults"]: break
        time.sleep(7)
    return out
def results(title, lines):
    open("RESULTS.md","w").write(f"# {title}\n\nGenerated by `real/run_real.py` on {TODAY}. Data are real public records (see DATA_SOURCES.md); nothing here is simulated. The bundled `fixtures/` remain SYNTHETIC teaching fixtures and are not used in these numbers.\n\n"+"\n".join(lines)+"\n")

import xml.etree.ElementTree as ET
ns={"a":"http://www.w3.org/2005/Atom","x":"http://arxiv.org/schemas/atom"}
q='cat:cs.CR AND (abs:"LLM agent" OR abs:"LLM agents" OR abs:"agentic" OR abs:"prompt injection")'
rows=[]
for start in range(0,400,100):
    x=get("https://export.arxiv.org/api/query?"+urllib.parse.urlencode({"search_query":q,"start":start,"max_results":100,"sortBy":"submittedDate","sortOrder":"descending"}),raw=True,timeout=120)
    for e in ET.fromstring(x).findall("a:entry",ns):
        txt=(e.findtext("a:summary","",ns)+" "+(e.findtext("x:comment","",ns) or ""))
        rows.append({"id":e.findtext("a:id","",ns),"published":e.findtext("a:published","",ns),"title":" ".join(e.findtext("a:title","",ns).split()),
          "code_link":bool(re.search(r"github\.com|gitlab|huggingface\.co|zenodo|anonymous\.4open|code (is|will be) (publicly )?available|open-source",txt,re.I))})
    time.sleep(4)
save("arxiv_agent_security_code_links.json",{"retrieved":TODAY,"query":q,"rows":rows})
n=len(rows); c=sum(r["code_link"] for r in rows)
yr=collections.defaultdict(lambda:[0,0])
for r in rows: yr[r["published"][:7]][0]+=1; yr[r["published"][:7]][1]+=r["code_link"]
L=[f"## Code/data availability signals in {n} recent arXiv cs.CR agent-security abstracts","",f"- Abstract or comment field links code or states availability: {c}/{n} ({100*c/max(1,n):.0f}%)",f"- Date range: {min(r['published'] for r in rows)[:10]} to {max(r['published'] for r in rows)[:10]}","","| month | papers | with code signal |","|---|---|---|"]+[f"| {k} | {v[0]} | {v[1]} |" for k,v in sorted(yr.items())]
L+=["","Absence from the abstract does not mean no artefact exists (many link code only in the PDF); this is a lower bound and the full-text audit is still needed."]
results("Demo 32 real data: artefact-availability signals on arXiv", L)
