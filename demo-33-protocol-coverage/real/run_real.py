#!/usr/bin/env python3
"""Fetch REAL public data for this demo and analyse it. Writes data/real/*.json and RESULTS.md.
Run from the demo folder: python3 real/run_real.py"""
import json, urllib.request, urllib.parse, time, datetime, os, collections, re, statistics
UA={"User-Agent":"agentic-security-demos research"}
def get(url, data=None, timeout=90, raw=False):
    err=None
    for i in range(5):
        try:
            req=urllib.request.Request(url, data=json.dumps(data).encode() if data else None, headers={**UA, **({"Content-Type":"application/json"} if data else {})})
            b=urllib.request.urlopen(req, timeout=timeout).read()
            return b.decode() if raw else json.loads(b)
        except Exception as e:
            err=e; time.sleep(7*(i+1))
    raise err
TODAY=datetime.date.today().isoformat()
def save(name, obj):
    os.makedirs("data/real", exist_ok=True)
    json.dump(obj, open(f"data/real/{name}","w"), indent=1, sort_keys=True)
def osv(eco, pkg):
    r=get("https://api.osv.dev/v1/query", {"package":{"name":pkg,"ecosystem":eco}})
    return [{"id":v["id"],"aliases":v.get("aliases",[]),"summary":v.get("summary",""),"published":v.get("published"),
             "severity":v.get("database_specific",{}).get("severity"),"cwe":v.get("database_specific",{}).get("cwe_ids",[]),
             "package":pkg,"ecosystem":eco} for v in r.get("vulns",[])]
def nvd(phrase):
    out=[];start=0
    while True:
        q=urllib.parse.urlencode({"keywordSearch":phrase,"keywordExactMatch":"","resultsPerPage":2000,"startIndex":start}).replace("keywordExactMatch=","keywordExactMatch")
        r=get("https://services.nvd.nist.gov/rest/json/cves/2.0?"+q)
        for v in r["vulnerabilities"]:
            c=v["cve"]; d=[x["value"] for x in c["descriptions"] if x["lang"]=="en"][0]
            cw=sorted({x["description"][0]["value"] for x in c.get("weaknesses",[])})
            out.append({"id":c["id"],"published":c["published"],"description":d,"cwe":cw})
        start+=r["resultsPerPage"]
        if start>=r["totalResults"]: break
        time.sleep(7)
    return out
def results(title, lines):
    open("RESULTS.md","w").write(f"# {title}\n\nGenerated by `real/run_real.py` on {TODAY}. Data are real public records (see DATA_SOURCES.md); nothing here is simulated. The bundled `fixtures/` remain SYNTHETIC teaching fixtures and are not used in these numbers.\n\n"+"\n".join(lines)+"\n")

servers=[];cur=None
while True:
    u="https://registry.modelcontextprotocol.io/v0/servers?limit=100"+("&cursor="+urllib.parse.quote(cur) if cur else "")
    r=get(u); servers+=r.get("servers",[]); cur=r.get("metadata",{}).get("nextCursor")
    if not cur or len(servers)>20000: break
rows=[]
for s in servers:
    v=s.get("server",s)
    rows.append({"name":v.get("name"),"version":v.get("version"),"remotes":[x.get("type") for x in v.get("remotes",[]) or []],
      "packages":[{"registry":p.get("registryType") or p.get("registry_type"),"transport":(p.get("transport") or {}).get("type")} for p in v.get("packages",[]) or []],
      "remote_headers":sum(len(x.get("headers",[]) or []) for x in v.get("remotes",[]) or [])})
save("mcp_registry_servers.json",{"retrieved":TODAY,"count":len(rows),"rows":rows})
latest={}
for r in rows: latest[r["name"]]=r
R=list(latest.values()); n=len(R)
rem=collections.Counter(t for r in R for t in r["remotes"]); reg=collections.Counter(p["registry"] for r in R for p in r["packages"]); tr=collections.Counter(p["transport"] for r in R for p in r["packages"])
remote_only=sum(1 for r in R if r["remotes"] and not r["packages"]); hdr=sum(1 for r in R if r["remotes"] and r["remote_headers"]>0); withrem=sum(1 for r in R if r["remotes"])
L=[f"## Official MCP Registry census ({len(rows)} entries, {n} distinct server names)","",f"- Servers offering a remote endpoint: {withrem} ({100*withrem/n:.0f}%); remote-only: {remote_only}","- Remote transport types: "+", ".join(f"{k}: {v}" for k,v in rem.most_common()),f"- Remote servers declaring at least one required header (e.g. an API key): {hdr}/{withrem}","- Package registries: "+", ".join(f"{k}: {v}" for k,v in reg.most_common()),"- Local package transports: "+", ".join(f"{k}: {v}" for k,v in tr.most_common()),"","The registry does not record whether a remote server implements the MCP OAuth authorisation flow, so authorisation coverage cannot be read from this census alone."]
results("Demo 33 real data: MCP Registry transport and deployment census", L)
